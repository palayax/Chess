/**
 * THE NARRATION STRING CONTRACT — every word the narrated review speaks or burns into a frame is
 * one of the [Sentence]s below, rendered by a [NarrationStrings] implementation for one language.
 *
 * `:core` is Android-free, so `R.string` is not available here; this file is what stands in for
 * it, and it is deliberately *not* a string table. The rule that shaped it:
 *
 * **A locale owns whole sentences, never fragments.** Hebrew inflects verbs and adjectives for
 * gender, pluralises differently and orders words differently, so `"White " + "played " + move`
 * cannot be translated piecewise no matter how good each piece is. Every [Sentence] therefore
 * carries *typed facts* (a [Subject] with person and gender, a [SpokenMove] with the piece, the
 * squares and the victim, a [Standing] enum rather than the English words for it) and a locale
 * builds the entire sentence from those facts in whatever order its grammar wants. The generator
 * never sees the words; it only chooses which sentence to say and joins finished sentences with
 * spaces.
 *
 * The English implementation is [EnglishNarration]. A translator receives:
 *  1. this file — the ids (class names), their parameters, and the English reference in the KDoc;
 *  2. `docs/NARRATION_STRINGS.md`, generated by [NarrationCatalogue] from the English
 *     implementation, one row per sentence with a rendered example;
 * and delivers one Kotlin object implementing [NarrationStrings]. The `when` over the sealed
 * hierarchy is exhaustive, so a sentence that was never translated is a compile error, not a
 * silent English fallback in the middle of a Hebrew review.
 *
 * Only a few things are *not* sentences and are joined by the generator: the discourse lead-ins
 * ([Sentence.ALittleLater], [Sentence.JumpTo]) that precede a beat, which are sentence adverbials
 * and read correctly as a prefix in either language; and the `.`/space that separates finished
 * sentences.
 */
interface NarrationStrings {

    /** BCP-47 tag of this language, e.g. `"en"`, `"he"`. */
    val languageTag: String

    /**
     * Every acceptable rendering of [sentence] in this language for [style], in a stable order.
     * The generator rotates through them deterministically ([PhrasePicker]) so a script does not
     * open forty beats with the same words. Never empty; a single-element list is the norm. A
     * locale may return more or fewer variants than English — the rotation adapts.
     *
     * An empty string is a legal variant only for [Sentence.Filler], and means "say nothing".
     */
    fun render(sentence: Sentence, style: NarrationStyle): List<String>

    /** The sub-sentence chess vocabulary this language uses; see [SpokenVocabulary]. */
    val vocabulary: SpokenVocabulary
}

/**
 * The parts of chess speech that are needed *outside* a whole sentence: by [NotationGuard] when
 * it has to speak notation that leaked in from a PGN tag, and by tests. Everything the generator
 * itself says goes through [NarrationStrings.render] as a whole [Sentence]; a locale is free to
 * compose these however its grammar wants inside those sentences.
 */
interface SpokenVocabulary {

    /** "f3" spoken so a TTS engine cannot misread it: English says "f three". */
    fun square(square: Square): String

    /** Lowercase piece noun: "knight". */
    fun piece(type: PieceType): String

    /** "White" / "Black". */
    fun side(color: Color): String

    /** A move as a noun phrase that can follow a verb: "knight takes the bishop on f three". */
    fun movePhrase(move: SpokenMove, includeOutcome: Boolean = true): String

    /** A whole variation as one breath: "pawn takes on e five, then bishop takes on f three". */
    fun linePhrase(moves: List<SpokenMove>): String

    /** Speakable form of notation that [NotationGuard] caught in free text. */
    fun spokenNotation(notation: ParsedNotation): String
}

// ---------------------------------------------------------------------------
// Typed facts that sentences carry
