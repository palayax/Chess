/** Grammatical person of a [Subject]: "you" or "White". */
enum class Person { SECOND, THIRD }

/**
 * Grammatical gender of a [Subject]. English never reads it; Hebrew must, because "you played"
 * is a different verb form for a woman than for a man. [UNSPECIFIED] is the honest default and
 * a locale should pick its conventional neutral form for it.
 */
enum class Gender { UNSPECIFIED, MASCULINE, FEMININE }

/**
 * Who a sentence is about. [person] is [Person.SECOND] when the viewer played this side and the
 * narration addresses them directly, [Person.THIRD] when the side is named by colour. [gender]
 * comes from [NarrationOptions.viewerGender] for the viewer and is [Gender.UNSPECIFIED] for the
 * opponent.
 */
data class Subject(
    val color: Color,
    val person: Person,
    val gender: Gender = Gender.UNSPECIFIED
)

enum class CastleSide { KINGSIDE, QUEENSIDE }

enum class MoveOutcome { NONE, CHECK, CHECKMATE }

/**
 * A move as facts, so a locale can say it its own way. Built by [SpokenChess.describe].
 *
 * @param captured the victim's type when this is a capture and the board knew what stood there.
 * @param ambiguous another piece of the same type could reach [to], so the origin must be spoken
 *   (the spoken equivalent of SAN disambiguation).
 */
data class SpokenMove(
    val color: Color,
    val piece: PieceType,
    val from: Square,
    val to: Square,
    val castle: CastleSide? = null,
    val isCapture: Boolean = false,
    val captured: PieceType? = null,
    val enPassant: Boolean = false,
    val promotion: PieceType? = null,
    val ambiguous: Boolean = false,
    val outcome: MoveOutcome = MoveOutcome.NONE
)

/** The verb a [Sentence.Played] uses. Semantic choices; a locale may render several the same. */
enum class MoveVerb { PLAY, GO_FOR, ANSWER_WITH, CONTINUE_WITH, REPLY_WITH, FOLLOW_UP_WITH, FIND }

/** Where in a missed-tactic excursion a [Sentence.ExcursionMove] sits. */
enum class ExcursionStep { FIRST, NEXT, REPLY }

/** How good a position is for its owner, from win-percent. See [NarrationVocabulary.standing]. */
enum class Standing {
    COMPLETELY_WINNING, WINNING, CLEARLY_BETTER, A_LITTLE_BETTER, ABOUT_LEVEL,
    SLIGHTLY_WORSE, CLEARLY_WORSE, LOSING, COMPLETELY_LOST
}

/** How much a move gave away. See [NarrationVocabulary.lossSeverity]. */
enum class LossSeverity { THE_WHOLE_GAME, MOST_OF_THE_ADVANTAGE, A_BIG_CHUNK, REAL_GROUND, A_LITTLE }

/** Spoken size of a tactic's material payoff. See [NarrationVocabulary.materialPayoff]. */
enum class MaterialPayoff { WHOLE_QUEEN, ROOK, PIECE, SERIOUS_MATERIAL, PAWN, BETTER_POSITION }

/** Material actually netted along a line, by unit. See [NarrationVocabulary.materialGain]. */
enum class MaterialGain { QUEEN, ROOK, PIECE, PAWN }

/** What a missed line delivers when it does not simply cash material or mate. */
enum class PayoffKind {
    DRAW_BY_REPETITION, STALEMATE, DESPERADO, PASSED_PAWN, SMALL_MATERIAL,
    KING_UNDER_FIRE, MATING_NET, INVESTED_MATERIAL, DECISIVE_ADVANTAGE
}

/** The prize a puzzle prompt promises. */
enum class PuzzlePrize { FORCES_MATE, WINS_ROOK_OR_BETTER, WINS_PIECE, WINS_MATERIAL }

/**
 * Opening families the narration has a plan blurb for, matched by substring of the book name
 * (first match wins, so specific names precede general ones). See
 * [NarrationVocabulary.openingFamily].
 */
enum class OpeningFamily(vararg val keywords: String) {
    PHILIDOR("Philidor"),
    PETROV("Petrov", "Russian Game"),
    RUY_LOPEZ("Ruy Lopez", "Spanish"),
    ITALIAN("Italian", "Giuoco"),
    SCOTCH("Scotch"),
    FOUR_KNIGHTS("Four Knights"),
    VIENNA("Vienna"),
    KINGS_GAMBIT("King's Gambit"),
    SICILIAN("Sicilian"),
    FRENCH("French"),
    CARO_KANN("Caro-Kann"),
    SCANDINAVIAN("Scandinavian"),
    PIRC_MODERN("Pirc", "Modern"),
    ALEKHINE("Alekhine"),
    QUEENS_GAMBIT("Queen's Gambit"),
    SLAV("Slav"),
    NIMZO("Nimzo"),
    KINGS_INDIAN("King's Indian"),
    GRUNFELD("Grunfeld"),
    BENONI("Benoni"),
    DUTCH("Dutch"),
    LONDON("London"),
    ENGLISH("English"),
    RETI("Reti"),
    BIRD("Bird")
}

/** Notation that [NotationGuard] found in free text, parsed so a locale can speak it. */
sealed interface ParsedNotation {
    data class Castle(val side: CastleSide) : ParsedNotation

    /** Nf3, Rad1, R1xd7, Qxh5+, e8=Q as a piece move. [fromFile] is 'a'..'h', [fromRank] 1..8. */
    data class PieceMove(
        val piece: PieceType,
        val fromFile: Char?,
        val fromRank: Int?,
        val capture: Boolean,
        val to: Square,
        val promotion: PieceType?,
        val outcome: MoveOutcome
    ) : ParsedNotation

    /** dxe5, exd8=Q+. */
    data class PawnCapture(val fromFile: Char, val to: Square, val promotion: PieceType?, val outcome: MoveOutcome) : ParsedNotation

    /** e8=Q, e4+ — a pawn push that carried a promotion or a check mark. */
    data class PawnPush(val to: Square, val promotion: PieceType?, val outcome: MoveOutcome) : ParsedNotation

    /** A bare "e4" in prose. */
    data class BareSquare(val square: Square) : ParsedNotation
}

